ProvaParaCorrecao provaCenario({
  int provaId = 1,
  List<String?> gabarito = gabaritoOriginal,
  List<String> letras = letrasAE,
}) => ProvaParaCorrecao(
  provaId: provaId,
  titulo: 'Cálculo I - Prova 2',
  questoes: [
    for (final (i, letra) in gabarito.indexed)
      QuestaoParaCorrecao(
        questaoId: 100 + i,
        numero: i + 1,
        letras: letras,
        letraCorreta: letra,
      ),
  ],
);

Map<int, Set<String>> respostasCenario(
  int aluno, {
  bool dupla = false,
  bool metade = false,
}) => {
  for (final (i, letra) in marcacoesOriginais[aluno].indexed)
    if ((!metade || i < 10) && letra != null)
      i + 1: {
        letra,
        if (dupla && i < 2)
          letra == 'E' ? 'A' : String.fromCharCode(letra.codeUnitAt(0) + 1),
      },
};
